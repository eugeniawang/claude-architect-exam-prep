#!/usr/bin/env node

const fs = require("fs");
const os = require("os");
const path = require("path");
const cp = require("child_process");

const sourceRoot = path.resolve(process.argv[2] || process.cwd());
const outputArg = process.argv[3];
const outputRoot = path.resolve(outputArg || path.join(sourceRoot, "dist", "cca-f-course-share"));
const runtimeEvidenceTemplate = path.join(sourceRoot, "templates", "runtime-evidence.md");

function runNode(args, cwd) {
  return cp.execFileSync("node", args, {
    cwd,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
}

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function removeDir(dir) {
  fs.rmSync(dir, { recursive: true, force: true });
}

function shouldSkip(entryName, rootLevel) {
  if (entryName === ".DS_Store") return true;
  if (rootLevel && entryName === "dist") return true;
  return false;
}

function copyDir(src, dest, rootLevel = false) {
  ensureDir(dest);
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    if (shouldSkip(entry.name, rootLevel)) continue;
    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);
    if (entry.isDirectory()) copyDir(srcPath, destPath, false);
    else if (entry.isFile()) fs.copyFileSync(srcPath, destPath);
  }
}

function resetRuntimeEvidence(destRoot) {
  const template = fs.readFileSync(runtimeEvidenceTemplate, "utf8");
  fs.writeFileSync(path.join(destRoot, "RUNTIME-EVIDENCE.md"), template.endsWith("\n") ? template : `${template}\n`);
}

function writeBuildNote(destRoot) {
  const note = [
    "# Share Package Build",
    "",
    "This folder was generated by `scripts/build-share-package.js`.",
    "",
    "Course version: 0.7",
    "Course last updated: 2026-06-08",
    `Source: ${sourceRoot}`,
    `Built: ${new Date().toISOString()}`,
    "",
    "Actions applied:",
    "- copied the course folder to a clean output directory",
    "- reset learner/course-local state in the copied folder",
    "- ran structural validation in the copied folder",
    "",
    "Next step for the receiving learner:",
    "- open this folder in Claude Code or another editor with Claude Code available",
    "- type `start`, `continue`, or `start next lesson`",
    "",
  ].join("\n");

  fs.writeFileSync(path.join(destRoot, "SHARE-PACKAGE-BUILD.md"), `${note}\n`);
}

function main() {
  const tempRoot = fs.mkdtempSync(path.join(os.tmpdir(), "cca-share-build-"));
  const stagingRoot = path.join(tempRoot, "claude-course");

  copyDir(sourceRoot, stagingRoot, true);
  runNode(["scripts/reset-course-state.js", "."], stagingRoot);
  resetRuntimeEvidence(stagingRoot);
  runNode(["scripts/validate-course.js", "."], stagingRoot);

  removeDir(outputRoot);
  ensureDir(path.dirname(outputRoot));
  copyDir(stagingRoot, outputRoot, false);
  writeBuildNote(outputRoot);

  console.log("CCA-F SHARE PACKAGE BUILT");
  console.log(`Source: ${sourceRoot}`);
  console.log(`Output: ${outputRoot}`);
  console.log("Verified in copy: reset state, validation");
}

try {
  main();
} catch (error) {
  console.error("CCA-F SHARE PACKAGE BUILD FAILED");
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
}
